-- Drop in dependency-safe order
DROP TABLE MusicReception CASCADE CONSTRAINTS;
DROP TABLE DonationLog CASCADE CONSTRAINTS;
DROP TABLE MusicLesson CASCADE CONSTRAINTS;
DROP TABLE InstrumentRepair CASCADE CONSTRAINTS;
DROP TABLE Payment CASCADE CONSTRAINTS;
DROP TABLE Instrument CASCADE CONSTRAINTS;
DROP TABLE Customer CASCADE CONSTRAINTS;

-- Customer
CREATE TABLE Customer (
    CustomerID      NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerName    VARCHAR2(100)   NOT NULL,
    CustomerEmail   VARCHAR2(100),
    CustomerPhone   VARCHAR2(20),
    CustomerAddress VARCHAR2(200),
    CONSTRAINT ck_customer_email CHECK (CustomerEmail IS NULL OR CustomerEmail LIKE '%@%.%')
);

-- Instrument catalog
CREATE TABLE Instrument (
    InstrumentName  VARCHAR2(50)    PRIMARY KEY,
    InstrumentLevel VARCHAR2(20)    NOT NULL,
    Price           NUMBER(10,2)    NOT NULL,
    CONSTRAINT ck_instrument_level CHECK (InstrumentLevel IN ('Beginner', 'Intermediate', 'Advanced', 'Professional')),
    CONSTRAINT ck_instrument_price CHECK (Price >= 0)
);

-- Instrument repair / service requests
CREATE TABLE InstrumentRepair (
    RepairID            NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID          NUMBER          NOT NULL,
    InstrumentName      VARCHAR2(50)    NOT NULL,
    RepairType          VARCHAR2(50)    NOT NULL,   -- cleaning, string replacement, fine tuning, parts repair, etc.
    RequestDate         DATE            DEFAULT SYSDATE,
    FinishDate          DATE,
    RepairPrice         NUMBER(10,2)    DEFAULT 0,
    Status              VARCHAR2(20)    DEFAULT 'Open',
    CONSTRAINT fk_repair_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID),
    CONSTRAINT fk_repair_instrument FOREIGN KEY (InstrumentName) REFERENCES Instrument(InstrumentName),
    CONSTRAINT ck_repair_status CHECK (Status IN ('Open', 'In Progress', 'Completed', 'Cancelled')),
    CONSTRAINT ck_repair_price CHECK (RepairPrice >= 0),
    CONSTRAINT ck_repair_dates CHECK (FinishDate IS NULL OR FinishDate >= RequestDate)
);

-- Music lessons
CREATE TABLE MusicLesson (
    MusicLessonID   NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID      NUMBER          NOT NULL,
    CompetencyLevel VARCHAR2(20)    NOT NULL,
    LessonType      VARCHAR2(30)    NOT NULL,   -- Group, Individual, etc.
    ClassSize       NUMBER          DEFAULT 1,
    ClassStartDate  DATE,
    ClassEndDate    DATE,
    LessonPrice     NUMBER(10,2)    NOT NULL,
    CONSTRAINT fk_lesson_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID),
    CONSTRAINT ck_lesson_level CHECK (CompetencyLevel IN ('Beginner', 'Intermediate', 'Advanced')),
    CONSTRAINT ck_lesson_price CHECK (LessonPrice >= 0),
    CONSTRAINT ck_lesson_size CHECK (ClassSize > 0),
    CONSTRAINT ck_lesson_dates CHECK (ClassEndDate IS NULL OR ClassEndDate >= ClassStartDate)
);

-- Payments (linked to a customer; supports mixed payment methods)
CREATE TABLE Payment (
    PaymentID       NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID      NUMBER          NOT NULL,
    PaymentDate     DATE            DEFAULT SYSDATE,
    Amount          NUMBER(10,2)    NOT NULL,
    CashAmount      NUMBER(10,2)    DEFAULT 0,
    CreditAmount    NUMBER(10,2)    DEFAULT 0,
    OtherAmount     NUMBER(10,2)    DEFAULT 0,
    PaymentStatus   VARCHAR2(10)    DEFAULT 'Pending',
    CONSTRAINT fk_payment_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID),
    CONSTRAINT ck_payment_status CHECK (PaymentStatus IN ('Pending', 'Paid', 'Overdue', 'Partial')),
    CONSTRAINT ck_payment_amounts CHECK (Amount >= 0 AND CashAmount >= 0 AND CreditAmount >= 0 AND OtherAmount >= 0)
);

-- Celebrity / fan instrument donations
CREATE TABLE DonationLog (
    DonationID      NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DonatorName     VARCHAR2(100)   NOT NULL,
    InstrumentName  VARCHAR2(50),
    DonationDate    DATE            DEFAULT SYSDATE,
    Notes           VARCHAR2(500),
    CONSTRAINT fk_donation_instrument FOREIGN KEY (InstrumentName) REFERENCES Instrument(InstrumentName)
);

-- Monthly music receptions
CREATE TABLE MusicReception (
    ReceptionID         NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MusicianName        VARCHAR2(100)   NOT NULL,
    InstrumentName      VARCHAR2(50),
    DonationID          NUMBER,                     -- optional link to a donated instrument
    CustomerParticipant NUMBER,
    VoteCountTotal      NUMBER          DEFAULT 0,
    ReceptionDate       DATE            NOT NULL,
    CONSTRAINT fk_reception_instrument FOREIGN KEY (InstrumentName) REFERENCES Instrument(InstrumentName),
    CONSTRAINT fk_reception_donation FOREIGN KEY (DonationID) REFERENCES DonationLog(DonationID),
    CONSTRAINT fk_reception_customer FOREIGN KEY (CustomerParticipant) REFERENCES Customer(CustomerID),
    CONSTRAINT ck_reception_votes CHECK (VoteCountTotal >= 0)
);

-- Helpful indexes
CREATE INDEX idx_repair_customer ON InstrumentRepair(CustomerID);
CREATE INDEX idx_lesson_customer ON MusicLesson(CustomerID);
CREATE INDEX idx_payment_customer ON Payment(CustomerID);
CREATE INDEX idx_payment_status ON Payment(PaymentStatus);
